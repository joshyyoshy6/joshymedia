"""
Make web-optimized WebP copies of the photos in assets/images/.

    python tools/optimize-images.py

- Only READS from assets/. It never moves, renames, edits or deletes anything there.
- Writes to images/<client>/[<project>/]<name>-large.webp  (longest side 2400px)
                                        <name>-small.webp  (shorter side 800px, for the 4:5 home grid)
  Folder names are made lowercase with dashes (e.g. "VUZE Magazine" -> "vuze-magazine")
  so links work on every web host.
- Also writes images/manifest.js, the list of photos (and their sizes) the site reads.
  Don't edit manifest.js by hand: it is rebuilt every time this script runs.
- Re-running is quick: photos whose copies are already up to date are skipped.

Folder rules (same as the site):
- A client folder with photos directly inside it = one project.
- A client folder with subfolders = each subfolder is its own project.
"""

import json
import re
import sys
from pathlib import Path

from PIL import Image, ImageOps

Image.MAX_IMAGE_PIXELS = None  # some originals are very large

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "images"
OUT = ROOT / "images"

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".webp", ".tif", ".tiff"}
SIZES = {"large": (2400, 82), "small": (800, 78)}  # name: (target px, webp quality); see make_copies


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def natural_key(stem):
    # "cover" first, then 1, 2, 3 ... 10 in number order
    return (stem.lower() != "cover", [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", stem)])


def images_in(folder):
    files = [p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in IMAGE_EXTS]
    return sorted(files, key=lambda p: natural_key(p.stem))


def find_projects():
    projects = []  # (folder key like "ditch/ruin", source folder)
    for client in sorted(p for p in SRC.iterdir() if p.is_dir()):
        if images_in(client):
            projects.append((slug(client.name), client))
        for sub in sorted(p for p in client.iterdir() if p.is_dir()):
            if images_in(sub):
                projects.append((f"{slug(client.name)}/{slug(sub.name)}", sub))
    return projects


def make_copies(src, dest_dir):
    stem = slug(src.stem)
    outputs = {k: dest_dir / f"{stem}-{k}.webp" for k in SIZES}
    up_to_date = all(o.exists() and o.stat().st_mtime >= src.stat().st_mtime for o in outputs.values())
    if not up_to_date:
        with Image.open(src) as im:
            im = ImageOps.exif_transpose(im)  # respect camera rotation
            if im.mode not in ("RGB", "RGBA"):
                im = im.convert("RGBA" if "A" in im.getbands() else "RGB")
            for key, (target, quality) in SIZES.items():
                copy = im.copy()
                if key == "small":
                    # small copies are cropped to tall 4:5 tiles, so size by the SHORTER side
                    scale = target / min(copy.size)
                    if scale < 1:
                        copy = copy.resize((round(copy.width * scale), round(copy.height * scale)), Image.LANCZOS)
                else:
                    copy.thumbnail((target, target), Image.LANCZOS)  # never enlarges
                copy.save(outputs[key], "WEBP", quality=quality, method=6)
    with Image.open(outputs["large"]) as large:
        w, h = large.size
    return {"name": stem, "w": w, "h": h}


def main():
    if not SRC.is_dir():
        sys.exit(f"Can't find {SRC}")
    manifest = {}
    for key, folder in find_projects():
        dest = OUT / key
        dest.mkdir(parents=True, exist_ok=True)
        manifest[key] = []
        for src in images_in(folder):
            manifest[key].append(make_copies(src, dest))
            print(f"  {key}/{src.name}")
    text = (
        "// AUTO-GENERATED by tools/optimize-images.py. Don't edit by hand.\n"
        "// Lists every optimized photo per project folder (w/h = large size in pixels).\n"
        "window.IMAGE_MANIFEST = " + json.dumps(manifest, indent=2) + ";\n"
    )
    (OUT / "manifest.js").write_text(text, encoding="utf-8")
    print(f"\nDone: {sum(len(v) for v in manifest.values())} photos in {len(manifest)} projects.")
    print("Project folders:", ", ".join(manifest))


if __name__ == "__main__":
    main()
